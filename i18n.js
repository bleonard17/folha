  function translate(raw){
    if(lang!=='pt')return raw;
    const m=raw.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if(!m)return raw;
    let body=m[2];
    if(!body)return raw;
    if(Object.hasOwn(pt,body))return m[1]+pt[body]+m[3];
    // Dynamic phrases such as "14/100 timing", "19 places" and named dates.
    body=body.replace(/(\d+)\s+places\b/g,'$1 locais')
      .replace(/(\d+)\s+place\b/g,'$1 local')
      .replace(/(\d+)\/100 timing\b/g,'$1/100 adequação')
      .replace(/(\d+) destinations nearby; zoom in to explore/g,'$1 destinos próximos; aproxime para explorar');
    for(const [en,value] of entries){
      if(en.length<5)continue;
      if(body.includes(en))body=body.split(en).join(value);
    }
    return m[1]+body+m[3];
  }
  function applyText(node){
    const before=original.has(node)?original.get(node):node.nodeValue;
    if(!original.has(node))original.set(node,before);
    const after=translate(before);
    if(node.nodeValue!==after)node.nodeValue=after;
  }
  function applyAttributes(node){
    if(!node||node.nodeType!==1)return;
    if(node.closest('#map'))return; // Don't rewrite MapLibre's own attribution controls.
    for(const attr of ['placeholder','aria-label','title']){
      if(!node.hasAttribute(attr))continue;
      let values=labels.get(node);
      if(!values){values={};labels.set(node,values)}
      if(!(attr in values))values[attr]=node.getAttribute(attr);
      const next=translate(values[attr]);
      if(node.getAttribute(attr)!==next)node.setAttribute(attr,next);
    }
  }
  function apply(root){
    if(!root)return;
    if(root.nodeType===3){applyText(root);return}
    if(root.nodeType!==1&&root.nodeType!==9)return;
    if(root.nodeType===1){
      if(root.closest('#map')||['SCRIPT','STYLE','NOSCRIPT','TEXTAREA'].includes(root.tagName))return;
      applyAttributes(root);
    }
    const walker=document.createTreeWalker(root,NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT);
    let node;
    while((node=walker.nextNode())){
      if(node.nodeType===1){
        if(node.closest('#map')||['SCRIPT','STYLE','NOSCRIPT','TEXTAREA'].includes(node.tagName)){walker.currentNode=node;continue}
        applyAttributes(node);
      }else if(node.parentElement && !node.parentElement.closest('#map,script,style,noscript,textarea'))applyText(node);
    }
  }
